function translateText(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || parent.closest("[data-no-translate],script,style,noscript")) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });
  let textNode;
  while ((textNode = walker.nextNode())) {
    const english = originalText.get(textNode) ?? textNode.data;
    if (!originalText.has(textNode)) originalText.set(textNode, english);
    const trimmed = english.trim();
    const translation = activeLanguage === "fil" ? filipinoTranslations[trimmed] : english;
    if (translation !== undefined) {
      const start = english.match(/^\s*/)?.[0] ?? "";
      const end = english.match(/\s*$/)?.[0] ?? "";
      textNode.data = `${start}${translation}${end}`;
    }
  }
}

function translateAttributes(root) {
  const elements = [root, ...root.querySelectorAll("[placeholder],[aria-label],[title]")];
  for (const element of elements) {
    if (!(element instanceof HTMLElement) || element.closest("[data-no-translate]")) continue;
    for (const attribute of ["placeholder", "aria-label", "title"]) {
      const current = element.getAttribute(attribute);
      if (current === null) continue;
      const originalAttribute = `data-language-original-${attribute}`;
      if (!element.hasAttribute(originalAttribute)) element.setAttribute(originalAttribute, current);
      const english = element.getAttribute(originalAttribute);
      const translation = activeLanguage === "fil" ? filipinoTranslations[english] : english;
      if (translation !== undefined) element.setAttribute(attribute, translation);
    }
  }
}

function updateLanguageUi() {
  languageCurrent.textContent = activeLanguage === "fil" ? "FIL" : "EN";
  languageToggle.setAttribute("aria-label", activeLanguage === "fil" ? "Pumili ng wika" : "Select language");
  languageMenu.setAttribute("aria-label", activeLanguage === "fil" ? "Wika" : "Language");
  languageMenu.querySelectorAll("[role=option]").forEach((option) => {
    option.setAttribute("aria-selected", String(option.dataset.language === activeLanguage));
  });
}

function setLanguage(language) {
  activeLanguage = language === "fil" ? "fil" : "en";
  document.documentElement.lang = activeLanguage;
  translateText(document.body);
  translateAttributes(document.body);
  document.title = activeLanguage === "fil" ? filipinoTranslations[originalTitle] ?? originalTitle : originalTitle;
  updateLanguageUi();
  try {
    localStorage.setItem(languageStorageKey, activeLanguage);
  } catch (error) {
    console.warn("Language preference could not be saved.", error);
  }
  document.dispatchEvent(new CustomEvent("enterseed:languagechange", { detail: { language: activeLanguage } }));
}

languageToggle.addEventListener("click", () => {
  const expanded = languageToggle.getAttribute("aria-expanded") === "true";
  languageToggle.setAttribute("aria-expanded", String(!expanded));
  languageMenu.hidden = expanded;
});

languageMenu.addEventListener("click", (event) => {
  const option = event.target.closest("[data-language]");
  if (!option) return;
  languageMenu.hidden = true;
  languageToggle.setAttribute("aria-expanded", "false");
  setLanguage(option.dataset.language);
  languageToggle.focus();
});

document.addEventListener("pointerdown", (event) => {
  if (!languagePicker.contains(event.target)) {
    languageMenu.hidden = true;
    languageToggle.setAttribute("aria-expanded", "false");
  }
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && !languageMenu.hidden) {
    languageMenu.hidden = true;
    languageToggle.setAttribute("aria-expanded", "false");
    languageToggle.focus();
  }
});

const languageObserver = new MutationObserver((records) => {
  for (const record of records) {
    if (record.type === "childList") {
      record.addedNodes.forEach((node) => {
        if (node instanceof HTMLElement || node instanceof DocumentFragment) {
          translateText(node);
          translateAttributes(node);
        } else if (node instanceof Text && activeLanguage === "fil") {
          const english = node.data;
          const translation = filipinoTranslations[english.trim()];
          if (translation) {
            originalText.set(node, english);
            node.data = translation;
          }
        }
      });
    }
  }
});

languageObserver.observe(document.body, { childList: true, subtree: true });
updateLanguageUi();
setLanguage(activeLanguage);

window.EnterseedLanguage = Object.freeze({
  get current() {
    return activeLanguage;
  }
});
